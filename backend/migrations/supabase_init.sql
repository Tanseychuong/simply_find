-- =============================================================================
-- EEL - full database setup for the live Supabase PostgreSQL
-- =============================================================================
-- Builds exactly what `python manage.py migrate` + `setup_groups` +
-- `setup_categories` would build on an empty database:
--
--   1. every table, index and constraint from all 27 Django migrations
--      (contenttypes, auth, accounts, admin, ingestion, opportunities, sessions)
--   2. django_migrations, marked fully applied, so Django won't re-run them
--   3. content types + model permissions (incl. can_verify_opportunity)
--   4. the "Moderators" group with can_verify_opportunity
--   5. the four starter opportunity categories
--   6. row-level security on every table, which blocks Supabase's public
--      REST API (anon/authenticated keys). Django is unaffected: it connects
--      as the table owner (postgres), which bypasses RLS.
--
-- Run it once, on an EMPTY database: Supabase -> SQL Editor -> paste -> Run,
-- or  psql "$DATABASE_URL" -f supabase_init.sql
-- It runs in one transaction and refuses to start if the tables already
-- exist, so a mistake leaves the database untouched.
--
-- Generated from backend/apps/*/migrations/ (Django 5.1.1). Later schema
-- changes go through `manage.py migrate` (the Render build runs it), not
-- edits to this file. Tables a later migration creates don't get RLS
-- automatically - enable it for them by hand.
--
-- Not included: the admin user. A Django password hash can't be made in
-- SQL; the Render build creates the admin from DJANGO_SUPERUSER_*
-- (docs/DEPLOY.md).
-- =============================================================================

BEGIN;

SET LOCAL search_path = public;

DO $$
BEGIN
    IF to_regclass('public.django_migrations') IS NOT NULL
       OR to_regclass('public.accounts_user') IS NOT NULL THEN
        RAISE EXCEPTION 'EEL tables already exist here - this script is for an empty database. Run `python manage.py migrate` instead.';
    END IF;
END $$;


